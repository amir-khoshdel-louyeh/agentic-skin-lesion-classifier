"""Generate a project-only, fully pinned dependency lock.

A raw `pip freeze` on a developer host includes unrelated system packages.
This resolves only the direct requirements declared in requirements.txt
and their installed transitive dependencies, evaluates environment
markers, and writes exact pins to requirements.lock.
"""

from __future__ import annotations

import argparse
import platform
import re
import sys
from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement

ROOT_DIR = Path(__file__).resolve().parent.parent


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def direct_requirements(path: Path) -> list[str]:
    names = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        names.append(Requirement(line).name)
    return names


def dependency_closure(path: Path) -> list[tuple[str, str]]:
    distributions = {
        canonical(dist.metadata["Name"]): dist
        for dist in metadata.distributions()
        if dist.metadata["Name"]
    }
    missing: list[str] = []
    seen: set[str] = set()
    queue = [canonical(name) for name in direct_requirements(path)]
    while queue:
        name = queue.pop(0)
        if name in seen:
            continue
        seen.add(name)
        dist = distributions.get(name)
        if dist is None:
            missing.append(name)
            continue
        for raw in dist.requires or []:
            requirement = Requirement(raw)
            if (requirement.marker is not None
                    and not requirement.marker.evaluate({"extra": ""})):
                continue
            queue.append(canonical(requirement.name))
    if missing:
        raise SystemExit(
            "Missing installed dependencies: " + ", ".join(sorted(missing))
        )
    return sorted(
        (distributions[name].metadata["Name"], distributions[name].version)
        for name in seen
    )


def render_lock(entries: list[tuple[str, str]]) -> str:
    lines = [
        "# Generated by tools/lock_requirements.py from requirements.txt.",
        f"# Python {platform.python_version()} "
        f"({platform.system().lower()}-{platform.machine().lower()})",
        "# Install with: python -m pip install -r requirements.lock",
        "",
    ]
    lines += [f"{name}=={version}" for name, version in entries]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate requirements.lock.")
    parser.add_argument("--requirements", default="requirements.txt")
    parser.add_argument("--output", default="requirements.lock")
    args = parser.parse_args()
    entries = dependency_closure(ROOT_DIR / args.requirements)
    out = ROOT_DIR / args.output
    out.write_text(render_lock(entries), encoding="utf-8")
    print(f"Wrote {out} with {len(entries)} pinned distributions.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
