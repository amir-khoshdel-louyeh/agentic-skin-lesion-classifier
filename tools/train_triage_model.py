#!/usr/bin/env python3
"""Train the compact 28x28 triage CNN used by ``tools/ham10000_cnn.py``.

The original development weights were never committed (``models/`` is
git-ignored), so this script rebuilds a usable triage model from the local
ISIC 2019 image tree. It writes exactly the files the wrapper expects:

    models/derm-cnn/model.py
    models/derm-cnn/labels.json
    models/derm-cnn/model.pth
    models/derm-cnn/calibration.json
    models/derm-cnn/metrics.json

Only the seven classes supported by ``ISIC_TO_CLASS`` are trained; SCC is
excluded because the wrapper has no mapping for it. The reported accuracy is
a held-out validation result for this compact model, not a reproduction of
the original calibration table.

Usage:
    .venv/bin/python tools/train_triage_model.py
    .venv/bin/python tools/train_triage_model.py --max-per-class 2500 --epochs 8
"""

from __future__ import annotations

import argparse
import json
import os
import random
from pathlib import Path

import numpy as np
from PIL import Image, ImageOps

BASE_DIR = Path(__file__).resolve().parent.parent
DEFAULT_DATASET = BASE_DIR / "dataset" / "ISIC2019_full"
DEFAULT_OUTPUT = BASE_DIR / "models" / "derm-cnn"

# label index -> ISIC/HAM code. Keep this order stable: the wrapper decodes
# predictions through labels.json using the same integer indices.
CLASS_DIRS = [
    ("AK", "akiec"),
    ("BCC", "bcc"),
    ("BKL", "bkl"),
    ("DF", "df"),
    ("MEL", "mel"),
    ("NV", "nv"),
    ("VASC", "vasc"),
]
LABELS = {str(index): code for index, (_, code) in enumerate(CLASS_DIRS)}

MODEL_SOURCE = '''"""Compact 28x28 dermoscopy triage CNN.

Generated by tools/train_triage_model.py. The wrapper imports this module to
rebuild the architecture before loading model.pth. The training checkpoint is
an nn.Sequential, so the loader must rebuild exactly that key layout.
"""

import torch
from torch import nn


def build_model(num_classes: int = 7) -> nn.Sequential:
    return nn.Sequential(
        nn.Conv2d(3, 32, 3, padding=1),
        nn.BatchNorm2d(32),
        nn.ReLU(inplace=True),
        nn.MaxPool2d(2),
        nn.Conv2d(32, 64, 3, padding=1),
        nn.BatchNorm2d(64),
        nn.ReLU(inplace=True),
        nn.MaxPool2d(2),
        nn.Conv2d(64, 128, 3, padding=1),
        nn.BatchNorm2d(128),
        nn.ReLU(inplace=True),
        nn.AdaptiveAvgPool2d(1),
        nn.Flatten(),
        nn.Dropout(0.2),
        nn.Linear(128, num_classes),
    )


def load_model(path: str, device: str = "cpu"):
    model = build_model()
    state = torch.load(path, map_location=device, weights_only=True)
    if isinstance(state, dict) and "state_dict" in state:
        state = state["state_dict"]
    model.load_state_dict(state)
    model.to(device).eval()
    return model, {"arch": "derm_cnn_small", "num_classes": 7}
'''


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", type=Path, default=DEFAULT_DATASET)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--max-per-class", type=int, default=1800,
                        help="Cap per class for reproducible CPU training; 0 uses all.")
    parser.add_argument("--epochs", type=int, default=6)
    parser.add_argument("--batch-size", type=int, default=128)
    parser.add_argument("--learning-rate", type=float, default=0.001)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--cache", type=Path, default=None,
                        help="Optional .npz cache; defaults to /tmp.")
    return parser.parse_args()


def load_uint8(path: Path) -> np.ndarray:
    with Image.open(path) as image:
        image = ImageOps.exif_transpose(image).convert("RGB")
        image = image.resize((28, 28), Image.Resampling.BILINEAR)
        return np.asarray(image, dtype=np.uint8)


def build_dataset(dataset: Path, max_per_class: int, seed: int,
                  cache: Path | None) -> tuple[np.ndarray, np.ndarray, list[Path]]:
    cache_path = cache or Path("/tmp") / f"isic28_7class_{max_per_class}_{seed}.npz"
    if cache_path.exists():
        payload = np.load(cache_path)
        print(f"Using cached tensors: {cache_path} ({len(payload['y'])} images)")
        return payload["x"], payload["y"], []

    rng = random.Random(seed)
    images: list[np.ndarray] = []
    labels: list[int] = []
    sources: list[Path] = []
    for index, (directory, _code) in enumerate(CLASS_DIRS):
        class_dir = dataset / directory
        paths = sorted(class_dir.glob("*.jpg"))
        if not paths:
            raise FileNotFoundError(f"No JPG images under {class_dir}")
        rng.shuffle(paths)
        if max_per_class > 0:
            paths = paths[:max_per_class]
        print(f"{directory}: {len(paths)} images")
        for position, path in enumerate(paths, start=1):
            try:
                images.append(load_uint8(path))
            except Exception as exc:  # noqa: BLE001 - report unreadable files
                print(f"skip {path}: {exc}")
                continue
            labels.append(index)
            sources.append(path)
            if position % 500 == 0:
                print(f"  loaded {position}/{len(paths)}")

    x = np.stack(images)
    y = np.asarray(labels, dtype=np.int64)
    cache_path.parent.mkdir(parents=True, exist_ok=True)
    np.savez(cache_path, x=x, y=y)
    print(f"Cached tensors to {cache_path}")
    return x, y, sources


def stratified_indices(y: np.ndarray, seed: int) -> tuple[np.ndarray, np.ndarray]:
    rng = np.random.default_rng(seed)
    train: list[int] = []
    val: list[int] = []
    for label in range(len(CLASS_DIRS)):
        indices = np.flatnonzero(y == label)
        rng.shuffle(indices)
        n_val = max(1, int(round(len(indices) * 0.2)))
        val.extend(indices[:n_val].tolist())
        train.extend(indices[n_val:].tolist())
    return (np.asarray(sorted(train), dtype=np.int64),
            np.asarray(sorted(val), dtype=np.int64))


def fit_temperature(logits: np.ndarray, y: np.ndarray) -> tuple[float, float]:
    best_t, best_nll = 1.0, float("inf")
    for temperature in np.linspace(0.5, 4.0, 141):
        shifted = logits / temperature
        shifted = shifted - shifted.max(axis=1, keepdims=True)
        log_probs = shifted - np.log(np.exp(shifted).sum(axis=1, keepdims=True))
        nll = float(-log_probs[np.arange(len(y)), y].mean())
        if nll < best_nll:
            best_t, best_nll = float(temperature), nll
    return round(best_t, 3), round(best_nll, 5)


def main() -> int:
    args = parse_args()
    import torch
    from torch import nn

    torch.manual_seed(args.seed)
    np.random.seed(args.seed)
    random.seed(args.seed)
    torch.set_num_threads(min(8, os.cpu_count() or 1))

    x, y, _sources = build_dataset(
        args.dataset, args.max_per_class, args.seed, args.cache)
    train_idx, val_idx = stratified_indices(y, args.seed)
    print(f"Train {len(train_idx)} / validation {len(val_idx)} / classes {len(CLASS_DIRS)}")

    x_tensor = torch.from_numpy(x).permute(0, 3, 1, 2).float() / 255.0
    x_tensor = (x_tensor - 0.5) / 0.25
    y_tensor = torch.from_numpy(y)
    train_x, train_y = x_tensor[train_idx], y_tensor[train_idx]
    val_x, val_y = x_tensor[val_idx], y_tensor[val_idx]

    counts = np.bincount(train_y.numpy(), minlength=len(CLASS_DIRS)).astype(float)
    weights = counts.sum() / (len(CLASS_DIRS) * np.maximum(counts, 1.0))
    criterion = nn.CrossEntropyLoss(
        weight=torch.tensor(weights, dtype=torch.float32))

    model = nn.Sequential(
        nn.Conv2d(3, 32, 3, padding=1), nn.BatchNorm2d(32), nn.ReLU(True),
        nn.MaxPool2d(2),
        nn.Conv2d(32, 64, 3, padding=1), nn.BatchNorm2d(64), nn.ReLU(True),
        nn.MaxPool2d(2),
        nn.Conv2d(64, 128, 3, padding=1), nn.BatchNorm2d(128), nn.ReLU(True),
        nn.AdaptiveAvgPool2d(1), nn.Flatten(), nn.Dropout(0.2),
        nn.Linear(128, len(CLASS_DIRS)),
    )
    optimizer = torch.optim.Adam(model.parameters(), lr=args.learning_rate)

    for epoch in range(1, args.epochs + 1):
        model.train()
        permutation = torch.randperm(len(train_x))
        running = 0.0
        for start in range(0, len(permutation), args.batch_size):
            batch_idx = permutation[start:start + args.batch_size]
            batch_x = train_x[batch_idx].clone()
            batch_y = train_y[batch_idx]
            flips = torch.rand(len(batch_x)) < 0.5
            if flips.any():
                batch_x[flips] = torch.flip(batch_x[flips], dims=[3])
            optimizer.zero_grad()
            loss = criterion(model(batch_x), batch_y)
            loss.backward()
            optimizer.step()
            running += float(loss.item()) * len(batch_x)
        model.eval()
        correct = 0
        with torch.no_grad():
            for start in range(0, len(val_x), args.batch_size):
                logits = model(val_x[start:start + args.batch_size])
                correct += int((logits.argmax(1) == val_y[start:start + args.batch_size]).sum())
        print(f"epoch {epoch}/{args.epochs}: loss={running / len(train_x):.4f} "
              f"val_acc={correct / len(val_x):.4f}")

    model.eval()
    val_logits: list[np.ndarray] = []
    val_predictions: list[int] = []
    with torch.no_grad():
        for start in range(0, len(val_x), args.batch_size):
            logits = model(val_x[start:start + args.batch_size])
            val_logits.append(logits.numpy())
            val_predictions.extend(logits.argmax(1).tolist())
    logits_array = np.concatenate(val_logits)
    temperature, nll = fit_temperature(logits_array, val_y.numpy())

    confusion = np.zeros((len(CLASS_DIRS), len(CLASS_DIRS)), dtype=int)
    for truth, prediction in zip(val_y.tolist(), val_predictions):
        confusion[truth, prediction] += 1
    per_class_recall = {}
    for index, (directory, code) in enumerate(CLASS_DIRS):
        total = int(confusion[index].sum())
        per_class_recall[code] = round(
            float(confusion[index, index] / total) if total else 0.0, 4)
    accuracy = float(np.trace(confusion) / confusion.sum())

    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "model.py").write_text(MODEL_SOURCE, encoding="utf-8")
    (args.output / "labels.json").write_text(
        json.dumps(LABELS, indent=2) + "\n", encoding="utf-8")
    (args.output / "calibration.json").write_text(
        json.dumps({"temperature": temperature, "validation_nll": nll}, indent=2) + "\n",
        encoding="utf-8")
    torch.save(model.state_dict(), args.output / "model.pth")
    metrics = {
        "training": "local ISIC 2019 rebuild",
        "classes": [code for _, code in CLASS_DIRS],
        "excluded": ["scc"],
        "train_samples": int(len(train_idx)),
        "validation_samples": int(len(val_idx)),
        "epochs": args.epochs,
        "seed": args.seed,
        "validation_accuracy": round(accuracy, 4),
        "per_class_recall": per_class_recall,
        "temperature": temperature,
        "validation_nll": nll,
        "confusion_matrix": confusion.tolist(),
    }
    (args.output / "metrics.json").write_text(
        json.dumps(metrics, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(metrics, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
